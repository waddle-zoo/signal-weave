def test_environment_binding_detects_installed_source_changes_not_bytecode(tmp_path):
    executable = tmp_path/"bin/mcp-superset"
    executable.parent.mkdir()
    executable.write_text("launcher")
    package = tmp_path/"lib/company.py"
    package.parent.mkdir()
    package.write_text("source")
    first = study.source_environment_identity(executable)
    (package.parent/"company.pyc").write_bytes(b"generated bytecode")
    assert study.source_environment_identity(executable) == first
    package.write_text("changed source")
    assert study.source_environment_identity(executable) != first


def test_warehouse_fingerprint_ignores_only_random_pg_markers(monkeypatch):
    responses = iter([b"\\restrict abc\nreal data\n\\unrestrict abc\n",
                      b"\\restrict xyz\nreal data\n\\unrestrict xyz\n",
                      b"\\restrict xyz\nchanged data\n\\unrestrict xyz\n"])
    calls = []

    def run(args, **kwargs):
        calls.append(args)
        return SimpleNamespace(returncode=0, stdout=next(responses))

    monkeypatch.setattr(study.subprocess, "run", run)
    first, second, third = (study.warehouse_fingerprint() for _ in range(3))
    assert first == second and second != third
    assert "--data-only" in calls[0][-1] and "pg_dump" in calls[0][-1]


